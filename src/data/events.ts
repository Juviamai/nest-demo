// Timestamps are generated relative to "today" so the demo always reads
// naturally, no matter when it is presented.
const dayOffset = (days: number): string => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return d.toISOString().slice(0, 10);
};
const at = (daysAgo: number, hhmm: string): string =>
  `${dayOffset(daysAgo)}T${hhmm}:00`;

